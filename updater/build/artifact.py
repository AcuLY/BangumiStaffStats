def make_checksum_inventory(artifacts: Path) -> tuple[bytes, list[dict[str, Any]]]:
    entries: list[dict[str, Any]] = []
    lines: list[str] = []
    for relative, path in _iter_regular_files(artifacts):
        digest = sha256_file(path)
        statement_path = f"artifacts/{relative}"
        entries.append(
            {
                "path": statement_path,
                "sha256": digest,
                "size": path.stat().st_size,
            }
        )
        lines.append(f"{digest}  {statement_path}\n")
    return "".join(lines).encode(), entries


def parse_checksum_inventory(value: bytes) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    paths: list[str] = []
    for line in value.decode("utf-8").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  ([^\s]+)", line)
        if match is None:
            raise BuildError("malformed SHA256SUMS line")
        path = _safe_relative(match.group(2)).as_posix()
        paths.append(path)
        entries.append({"path": path, "sha256": match.group(1)})
    if not entries:
        raise BuildError("SHA256SUMS must not be empty")
    if paths != sorted(paths) or len(paths) != len(set(paths)):
        raise BuildError("SHA256SUMS paths must be unique and sorted")
    return entries


def verify_output(output: Path, *, require_statement: bool) -> None:
    if output.is_symlink() or not output.is_dir():
        raise BuildError("artifact output must be a real directory")
    for relative, _path in _iter_regular_files(output):
        _safe_relative(relative)
    expected_evidence = {"SHA256SUMS", "sbom.spdx.json"}
    if require_statement:
        expected_evidence.add("component-statement.json")
    actual_evidence = {
        path.name for path in output.iterdir() if path.is_file() and path.name in EVIDENCE_FILES
    }
    if actual_evidence != expected_evidence:
        raise BuildError("artifact evidence file set is incomplete or unexpected")
    inventory = parse_checksum_inventory((output / "SHA256SUMS").read_bytes())
    expected_paths = [relative for relative, _path in _iter_regular_files(output / "artifacts")]
    expected_paths = [f"artifacts/{value}" for value in expected_paths]
    if [item["path"] for item in inventory] != expected_paths:
        raise BuildError("SHA256SUMS does not exactly cover artifact files")
    for entry in inventory:
        path = output.joinpath(*PurePosixPath(entry["path"]).parts)
        if sha256_file(path) != entry["sha256"]:
            raise BuildError(f"artifact checksum mismatch: {entry['path']}")
    try:
        sbom = json.loads((output / "sbom.spdx.json").read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise BuildError(f"invalid SPDX JSON: {error}") from error
    if sbom.get("spdxVersion") != "SPDX-2.3":
        raise BuildError("SPDX version must be SPDX-2.3")
    if canonical_json(sbom) != (output / "sbom.spdx.json").read_bytes():
        raise BuildError("SPDX JSON is not canonical")
    verify_spdx_artifact_coverage(sbom, inventory)
    if require_statement:
        try:
            statement = json.loads(
                (output / "component-statement.json").read_text(encoding="utf-8")
            )
        except json.JSONDecodeError as error:
            raise BuildError(f"invalid component statement JSON: {error}") from error
        if canonical_json(statement) != (output / "component-statement.json").read_bytes():
            raise BuildError("component statement JSON is not canonical")


def compare_trees(first: Path, second: Path) -> None:
    first_files = _iter_regular_files(first)
    second_files = _iter_regular_files(second)
    first_paths = [relative for relative, _path in first_files]
    second_paths = [relative for relative, _path in second_files]
    if first_paths != second_paths:
        raise BuildError("repeated builds emitted different file inventories")
    for (relative, first_path), (_other, second_path) in zip(
        first_files, second_files, strict=True
    ):
        if first_path.read_bytes() != second_path.read_bytes():
            raise BuildError(f"repeated builds differ: {relative}")


def publish_content_addressed(stage: Path, publish_root: Path) -> Path:
    stage = _require_under_tmp(stage)
    if stage.is_symlink() or not stage.is_dir():
        raise BuildError("content-addressed source must be a real generated directory")
    publish_root = _ensure_generated_directory(publish_root)
    digest = tree_digest(stage)
    destination = publish_root / f"sha256-{digest}"
    destination = _require_under_tmp(destination)
    if os.path.lexists(destination):
        if destination.is_symlink() or not destination.is_dir():
            raise BuildError("content-addressed destination must be a real directory")
        compare_trees(stage, destination)
        return destination
    _require_under_tmp(publish_root)
    temporary = Path(
        tempfile.mkdtemp(
            dir=publish_root,
            prefix=f".{destination.name}.",
            suffix=".publishing",
        )
    )
    _require_under_tmp(temporary)
    try:
        _require_under_tmp(publish_root)
        _require_under_tmp(temporary)
        shutil.copytree(stage, temporary, dirs_exist_ok=True)
        compare_trees(stage, temporary)
        try:
            _require_under_tmp(destination)
            _require_under_tmp(temporary)
            temporary.rename(destination)
        except OSError as error:
            if error.errno not in {errno.EEXIST, errno.ENOTEMPTY}:
                raise
            if destination.is_symlink() or not destination.is_dir():
                raise BuildError(
                    "content-addressed destination must be a real directory"
                ) from error
            compare_trees(stage, destination)
    finally:
        if os.path.lexists(temporary):
            _remove_generated_directory(temporary)
    return destination


def _emit_contract_statement(
    *,
    stage: Path,
    identity: SourceIdentity,
    target: Target,
    inventory: Sequence[Mapping[str, Any]],
    metadata: Mapping[str, Any],
    contracts_root: Path,
) -> None:
    helper_path = contracts_root / "artifacts" / "statement.py"
    if helper_path.is_symlink() or not helper_path.is_file():
        raise BuildError(f"Contracts statement helper is missing: {helper_path}")
    specification = importlib.util.spec_from_file_location(
        "_bgmss_contracts_artifact_statement",
        helper_path,
    )
    if specification is None or specification.loader is None:
        raise BuildError(f"Contracts statement helper cannot be loaded: {helper_path}")
    try:
        module = importlib.util.module_from_spec(specification)
        specification.loader.exec_module(module)
        emit_component_statement = module.emit_component_statement
        statement = emit_component_statement(
            artifacts=inventory,
            checksum_path="SHA256SUMS",
            checksum_sha256=sha256_file(stage / "SHA256SUMS"),
            checksum_size=(stage / "SHA256SUMS").stat().st_size,
            contracts_root=contracts_root,
            metadata=metadata,
            sbom_path="sbom.spdx.json",
            sbom_sha256=sha256_file(stage / "sbom.spdx.json"),
            sbom_size=(stage / "sbom.spdx.json").stat().st_size,
            source_revision=identity.revision,
            source_tree=identity.tree,
            target_architecture=target.architecture,
            target_os=target.os,
        )
    except (AttributeError, ImportError, OSError, TypeError, ValueError) as error:
        raise BuildError(f"Contracts statement emission failed: {error}") from error
    _write_bytes(stage / "component-statement.json", canonical_json(statement))


def validate_contract_output(stage: Path, contracts_root: Path) -> None:
    validator = contracts_root / "artifacts" / "lib" / "validation.mjs"
    if validator.is_symlink() or not validator.is_file():
        raise BuildError(f"Contracts artifact validator is missing: {validator}")
    node = shutil.which("node")
    if node is None:
        raise BuildError("Node.js is required for strict Contracts artifact validation")
    program = (
        f"import {{ verifyComponentDirectory }} from {json.dumps(validator.resolve().as_uri())};"
        "verifyComponentDirectory(process.argv[1], 'updater');"
    )
    _run(
        [node, "--input-type=module", "--eval", program, str(stage.resolve())],
        cwd=REPOSITORY_ROOT,
        capture=True,
    )


def build_component(
    *,
    work_root: Path,
    target: Target,
    attestation: SourceAttestation,
    uv: Path,
    python: Path,
    docker: Path | None,
    contracts_root: Path | None,
    publish_root: Path | None,
    builder: str | None = None,
) -> Path:
    identity = attestation.identity
    identity.validate()
    work_root = _require_under_tmp(work_root)
    _clear_generated_directory(work_root)
    _verify_toolchain(uv, python)
    verified_builder: str | None = None
    if docker is not None:
        verified_builder = _verify_docker_toolchain(docker, builder=builder)
    snapshot = work_root / "source"
    _copy_source_snapshot(snapshot, attestation)
    input_digest = tree_digest(snapshot)
    stage = work_root / "output"
    artifacts = stage / "artifacts"
    _ensure_generated_directory(artifacts)
    wheel, bundle, runtime_packages = _build_wheel_and_bundle(
        snapshot=snapshot,
        work_root=work_root,
        artifacts=artifacts,
        uv=uv,
        python=python,
        target=target,
        identity=identity,
    )
    image_path: Path | None = None
    image_metadata: Mapping[str, Any] | None = None
    if docker is not None:
        if verified_builder is None:
            raise BuildError("Docker build requires a verified Buildx builder")
        image_path, image_metadata = _build_oci(
            snapshot=snapshot,
            work_root=work_root,
            artifacts=artifacts,
            target=target,
            identity=identity,
            docker=docker,
            builder=verified_builder,
        )
    artifact_package_count = len(_iter_regular_files(artifacts)) + 1
    metadata: dict[str, Any] = {
        "artifacts": {
            "bundle": {
                "path": f"artifacts/{bundle.name}",
                "sha256": sha256_file(bundle),
                "size": bundle.stat().st_size,
            },
            "image": (
                {
                    "oci": image_metadata,
                    "path": f"artifacts/{image_path.name}",
                    "sha256": sha256_file(image_path),
                    "size": image_path.stat().st_size,
                }
                if image_path is not None
                else None
            ),
            "wheel": {
                **_wheel_metadata(wheel),
                "path": f"artifacts/{wheel.name}",
                "sha256": sha256_file(wheel),
                "size": wheel.stat().st_size,
            },
        },
        "buildDefinitionSha256": _build_definition_digest(),
        "component": COMPONENT_ID,
        "inputs": {
            "sourceSnapshotSha256": input_digest,
            "uvLockSha256": sha256_file(snapshot / "uv.lock"),
        },
        "runtimePackages": runtime_packages,
        "schemaVersion": "bgmss-updater-build-metadata-v1",
        "sbomPackageCount": artifact_package_count + len(runtime_packages) - 1,
        "source": {"revision": identity.revision, "tree": identity.tree},
        "target": {"architecture": target.architecture, "os": target.os},
        "toolchain": {
            "buildkit": BUILDKIT_VERSION,
            "buildkitImage": BUILDKIT_IMAGE,
            "dockerBuildx": DOCKER_BUILDX_VERSION,
            "python": PYTHON_VERSION,
            "pythonBaseImage": PYTHON_IMAGE,
            "uv": UV_VERSION,
            "uvBaseImage": UV_IMAGE,
        },
    }
    _write_bytes(artifacts / "build-metadata.json", canonical_json(metadata))
    checksum_bytes, inventory = make_checksum_inventory(artifacts)
    _write_bytes(stage / "SHA256SUMS", checksum_bytes)
    _write_bytes(
        stage / "sbom.spdx.json",
        canonical_json(
            make_spdx(
                artifacts=inventory,
                dependency_artifact_path=f"artifacts/{bundle.name}",
                runtime_packages=runtime_packages,
                lock_path=snapshot / "uv.lock",
                namespace_digest=sha256_file(bundle),
            )
        ),
    )
    require_statement = contracts_root is not None
    if contracts_root is not None:
        _emit_contract_statement(
            stage=stage,
            identity=identity,
            target=target,
            inventory=inventory,
            metadata=metadata,
            contracts_root=contracts_root.resolve(),
        )
    verify_output(stage, require_statement=require_statement)
    if contracts_root is not None:
        validate_contract_output(stage, contracts_root)
    if publish_root is not None:
        if docker is None or contracts_root is None:
            raise BuildError("partial native output cannot be content-address published")
        return publish_content_addressed(stage, publish_root)
    return stage


def verify_dockerfile(path: Path = UPDATER_ROOT / "Dockerfile") -> None:
    value = path.read_text(encoding="utf-8")
    expected_from = [
        f"FROM {UV_IMAGE} AS uv-bin",
        f"FROM {PYTHON_IMAGE} AS builder",
        f"FROM {PYTHON_IMAGE} AS runtime",
    ]
    from_lines = [line for line in value.splitlines() if line.startswith("FROM ")]
    if from_lines != expected_from:
        raise BuildError("Dockerfile FROM lines are not the exact reviewed digest pins")
    if any(line.startswith("ARG ") and "IMAGE" in line for line in value.splitlines()):
        raise BuildError("Dockerfile base pins must not be overrideable build arguments")
    if value.count("USER 65532:65532") != 1:
        raise BuildError("Dockerfile must set exactly one final non-root user")
    required = {
        "ENTRYPOINT": "one-shot entrypoint",
        "PATH=/usr/local/bin:/usr/bin:/bin": "runtime command path",
        "uv sync --frozen": "frozen dependency install",
        "uv build --offline --wheel": "offline wheel build",
        "uv pip install --offline": "offline runtime install",
        "runtime_prune.py /opt/runtime": "runtime development-content pruning",
        "/usr/local/lib/python3.14/site-packages/pip": "pip removal",
        "test ! -e /usr/local/bin/uv": "uv absence check",
        "test ! -e /src": "source absence check",
    }
    for needle, purpose in required.items():
        if needle not in value:
            raise BuildError(f"Dockerfile is missing {purpose}")
    forbidden = (
        "current.json",
        "update_activated",
        "systemd",
        "crond",
        "docker push",
        "registry login",
    )
    lowered = value.lower()
    for needle in forbidden:
        if needle in lowered:
            raise BuildError(f"Dockerfile contains forbidden behavior: {needle}")


def _path_argument(value: str) -> Path:
    return Path(value).expanduser()


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(allow_abbrev=False)
    subcommands = parser.add_subparsers(dest="command", required=True)
    build = subcommands.add_parser("build", allow_abbrev=False)
    build.add_argument("--work-root", required=True, type=_path_argument)
    build.add_argument("--target", default="linux/arm64")
    build.add_argument("--source-revision")
    build.add_argument("--source-tree")
    build.add_argument("--source-date-epoch", type=int)
    build.add_argument("--uv", type=_path_argument, default=Path(shutil.which("uv") or "uv"))
    build.add_argument("--python", required=True, type=_path_argument)
    build.add_argument("--docker", type=_path_argument)
    build.add_argument("--builder")
    build.add_argument("--contracts-root", type=_path_argument)
    build.add_argument("--publish-root", type=_path_argument)
    verify = subcommands.add_parser("verify", allow_abbrev=False)
    verify.add_argument("output", type=_path_argument)
    verify.add_argument("--without-statement", action="store_true")
    compare = subcommands.add_parser("compare", allow_abbrev=False)
    compare.add_argument("first", type=_path_argument)
    compare.add_argument("second", type=_path_argument)
    subcommands.add_parser("verify-dockerfile", allow_abbrev=False)
    return parser


def main(arguments: Sequence[str] | None = None) -> int:
    namespace = _parser().parse_args(arguments)
    try:
        if namespace.command == "build":
            attestation = attest_source_checkout(
                namespace.source_revision,
                namespace.source_tree,
                namespace.source_date_epoch,
            )
            output = build_component(
                work_root=namespace.work_root,
                target=Target.parse(namespace.target),
                attestation=attestation,
                uv=namespace.uv.resolve(),
                python=namespace.python.resolve(),
                docker=namespace.docker.resolve() if namespace.docker else None,
                contracts_root=(
                    namespace.contracts_root.resolve() if namespace.contracts_root else None
                ),
                publish_root=namespace.publish_root,
                builder=namespace.builder,
            )
            sys.stdout.write(f"{output}\n")
            return 0
        if namespace.command == "verify":
            verify_output(
                namespace.output.resolve(), require_statement=not namespace.without_statement
            )
            return 0
        if namespace.command == "compare":
            compare_trees(namespace.first.resolve(), namespace.second.resolve())
            return 0
        if namespace.command == "verify-dockerfile":
            verify_dockerfile()
            return 0
        raise BuildError("unknown command")
    except BuildError as error:
        sys.stderr.write(f"updater artifact error: {error}\n")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
