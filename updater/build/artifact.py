def canonical_json(value: Any) -> bytes:
    """Return newline-terminated canonical JSON bytes."""
    try:
        encoded = json.dumps(
            value,
            allow_nan=False,
            ensure_ascii=False,
            separators=(",", ":"),
            sort_keys=True,
        )
    except (TypeError, ValueError) as error:
        raise BuildError(f"value is not canonical JSON: {error}") from error
    return f"{encoded}\n".encode()


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _safe_relative(value: str) -> PurePosixPath:
    if "\\" in value or "\0" in value:
        raise BuildError(f"unsafe relative path: {value!r}")
    path = PurePosixPath(value)
    if (
        not value
        or path.is_absolute()
        or value != path.as_posix()
        or any(
            part in {"", ".", ".."} or re.fullmatch(r"[A-Za-z0-9._-]+", part) is None
            for part in path.parts
        )
    ):
        raise BuildError(f"unsafe relative path: {value!r}")
    return path


def _tmp_root_path() -> Path:
    root = TMP_ROOT.absolute()
    if os.path.lexists(root) and (root.is_symlink() or not root.is_dir()):
        raise BuildError(f"generated root must be a real directory: {root}")
    return root


def _ensure_tmp_root() -> Path:
    root = _tmp_root_path()
    if not root.exists():
        if root.parent.is_symlink() or not root.parent.is_dir():
            raise BuildError(f"generated root parent must be a real directory: {root.parent}")
        root.mkdir()
    return _tmp_root_path()


def _require_under_tmp(path: Path) -> Path:
    raw = Path(path)
    if any(part == ".." for part in raw.parts):
        raise BuildError(f"generated path contains a parent traversal: {raw}")
    candidate = raw.absolute()
    root = _tmp_root_path()
    try:
        relative = candidate.relative_to(root)
    except ValueError as error:
        raise BuildError(f"generated path must be below {root}") from error
    if relative == Path():
        raise BuildError(f"generated path must be below {root}")

    current = root
    for index, part in enumerate(relative.parts):
        current /= part
        if not os.path.lexists(current):
            continue
        if current.is_symlink():
            raise BuildError(f"generated path contains a symlink: {current}")
        if index < len(relative.parts) - 1 and not current.is_dir():
            raise BuildError(f"generated path parent is not a directory: {current}")
    return candidate


def _ensure_generated_directory(path: Path) -> Path:
    candidate = _require_under_tmp(path)
    root = _ensure_tmp_root()
    current = root
    for part in candidate.relative_to(root).parts:
        current /= part
        if os.path.lexists(current):
            if current.is_symlink() or not current.is_dir():
                raise BuildError(f"generated directory is not a real directory: {current}")
        else:
            current.mkdir()
        _require_under_tmp(current)
    return candidate


def _ensure_generated_parent(path: Path) -> Path:
    candidate = _require_under_tmp(path)
    root = _ensure_tmp_root()
    if candidate.parent != root:
        _ensure_generated_directory(candidate.parent)
    return candidate


def _remove_generated_directory(path: Path) -> None:
    candidate = _require_under_tmp(path)
    if os.path.lexists(candidate):
        if candidate.is_symlink() or not candidate.is_dir():
            raise BuildError(f"refusing to remove non-directory output: {candidate}")
        _require_under_tmp(candidate)
        shutil.rmtree(candidate)


def _unlink_generated_file(path: Path, *, missing_ok: bool = False) -> None:
    candidate = _require_under_tmp(path)
    if not os.path.lexists(candidate):
        if missing_ok:
            return
        raise BuildError(f"generated file does not exist: {candidate}")
    if candidate.is_symlink() or not candidate.is_file():
        raise BuildError(f"refusing to remove non-file output: {candidate}")
    _require_under_tmp(candidate)
    candidate.unlink()


def _clear_generated_directory(path: Path) -> None:
    candidate = _require_under_tmp(path)
    _remove_generated_directory(candidate)
    _ensure_generated_directory(candidate)


def _write_bytes(path: Path, value: bytes, *, mode: int = 0o644) -> None:
    path = _ensure_generated_parent(path)
    if os.path.lexists(path) and (path.is_symlink() or not path.is_file()):
        raise BuildError(f"refusing to replace non-file output: {path}")
    temporary = _require_under_tmp(path.with_name(f".{path.name}.writing"))
    if os.path.lexists(temporary) and (temporary.is_symlink() or not temporary.is_file()):
        raise BuildError(f"refusing to replace non-file temporary output: {temporary}")
    temporary.write_bytes(value)
    temporary.chmod(mode)
    _require_under_tmp(path)
    _require_under_tmp(temporary)
    temporary.replace(path)


def _copy_generated_file(source: Path, destination: Path, *, mode: int | None = None) -> None:
    if source.is_symlink() or not source.is_file():
        raise BuildError(f"generated input must be a real file: {source}")
    destination = _ensure_generated_parent(destination)
    if os.path.lexists(destination) and (destination.is_symlink() or not destination.is_file()):
        raise BuildError(f"refusing to replace non-file output: {destination}")
    shutil.copyfile(source, destination)
    if mode is not None:
        destination.chmod(mode)


def _copy_generated_stream(source: Any, destination: Path, *, mode: int = 0o644) -> None:
    destination = _ensure_generated_parent(destination)
    if os.path.lexists(destination) and (destination.is_symlink() or not destination.is_file()):
        raise BuildError(f"refusing to replace non-file output: {destination}")
    temporary = _require_under_tmp(destination.with_name(f".{destination.name}.writing"))
    if os.path.lexists(temporary) and (temporary.is_symlink() or not temporary.is_file()):
        raise BuildError(f"refusing to replace non-file temporary output: {temporary}")
    with temporary.open("wb") as output:
        shutil.copyfileobj(source, output)
    temporary.chmod(mode)
    _require_under_tmp(destination)
    _require_under_tmp(temporary)
    temporary.replace(destination)


def _run(
    command: Sequence[str],
    *,
    cwd: Path,
    env: Mapping[str, str] | None = None,
    capture: bool = False,
) -> str:
    rendered = " ".join(command)
    sys.stdout.write(f"+ {rendered}\n")
    sys.stdout.flush()
    completed = subprocess.run(  # noqa: S603
        list(command),
        check=False,
        cwd=cwd,
        env=dict(env) if env is not None else None,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        text=True,
    )
    if completed.returncode != 0:
        detail = ""
        if capture:
            detail = f"\nstdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
        raise BuildError(f"command failed ({completed.returncode}): {rendered}{detail}")
    return completed.stdout.strip() if capture else ""


def _git_output(*arguments: str) -> str:
    return _run(
        ["git", *arguments],
        cwd=REPOSITORY_ROOT,
        capture=True,
    )


def _attestation_git_raw(
    repository_root: Path,
    *arguments: str,
    input_data: bytes | None = None,
) -> subprocess.CompletedProcess[bytes]:
    environment = {
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_NO_REPLACE_OBJECTS": "1",
        "GIT_OPTIONAL_LOCKS": "0",
        "LC_ALL": "C",
        "PATH": os.environ.get("PATH", os.defpath),
    }
    git = shutil.which("git")
    if git is None:
        raise BuildError("Git is required for source checkout attestation")
    try:
        return subprocess.run(  # noqa: S603
            [
                git,
                "-c",
                "core.fsmonitor=false",
                "-c",
                "core.untrackedCache=false",
                *arguments,
            ],
            check=False,
            cwd=repository_root,
            env=environment,
            capture_output=True,
            input=input_data,
        )
    except OSError as error:
        raise BuildError(f"cannot inspect canonical Git checkout: {error}") from error


def _attestation_error(completed: subprocess.CompletedProcess[bytes]) -> str:
    detail = completed.stderr.decode("utf-8", errors="replace").strip()
    return f": {detail}" if detail else ""


def _attestation_git_output(
    repository_root: Path,
    *arguments: str,
    allow_empty: bool = False,
) -> str:
    completed = _attestation_git_raw(repository_root, *arguments)
    if completed.returncode != 0:
        raise BuildError(f"cannot derive source identity from Git{_attestation_error(completed)}")
    try:
        value = completed.stdout.decode("utf-8").strip()
    except UnicodeDecodeError as error:
        raise BuildError("Git returned a non-UTF-8 source identity value") from error
    if not value and not allow_empty:
        raise BuildError("Git returned an empty source identity value")
    return value


def _attestation_git_bytes(
    repository_root: Path,
    *arguments: str,
) -> bytes:
    completed = _attestation_git_raw(repository_root, *arguments)
    if completed.returncode != 0:
        raise BuildError(f"cannot inspect tracked Git state{_attestation_error(completed)}")
    return completed.stdout


def _nul_records(value: bytes, description: str) -> tuple[bytes, ...]:
    if not value:
        return ()
    if not value.endswith(b"\0"):
        raise BuildError(f"{description} is not NUL terminated")
    records = tuple(value[:-1].split(b"\0"))
    if any(not record for record in records):
        raise BuildError(f"{description} contains an empty record")
    return records


def _decode_git_path(value: bytes) -> str:
    path = os.fsdecode(value)
    parsed = PurePosixPath(path)
    if (
        not path
        or parsed.is_absolute()
        or parsed.as_posix() != path
        or any(part in {"", ".", ".."} for part in parsed.parts)
    ):
        raise BuildError(f"Git reported an unsafe tracked path: {path!r}")
    return path


def _validate_git_oid(value: bytes, object_format: str) -> str:
    try:
        oid = value.decode("ascii")
    except UnicodeDecodeError as error:
        raise BuildError("Git reported a non-ASCII object id") from error
    expected_length = {"sha1": 40, "sha256": 64}[object_format]
    if len(oid) != expected_length or not GIT_OBJECT_RE.fullmatch(oid):
        raise BuildError(f"Git reported an invalid {object_format} object id")
    return oid


def _parse_head_entries(value: bytes, object_format: str) -> dict[str, _GitEntry]:
    entries: dict[str, _GitEntry] = {}
    for record in _nul_records(value, "HEAD tree"):
        try:
            metadata, path_value = record.split(b"\t", 1)
            mode_value, object_type, oid_value = metadata.split(b" ", 2)
        except ValueError as error:
            raise BuildError("HEAD tree contains a malformed record") from error
        if object_type != b"blob" or mode_value not in {b"100644", b"100755"}:
            raise BuildError("HEAD tree must contain only tracked regular blobs")
        path = _decode_git_path(path_value)
        if path in entries:
            raise BuildError(f"HEAD tree contains a duplicate path: {path!r}")
        entries[path] = _GitEntry(
            path=path,
            mode=int(mode_value, 8),
            oid=_validate_git_oid(oid_value, object_format),
        )
    if not entries:
        raise BuildError("HEAD tree contains no tracked regular blobs")
    return entries


def _parse_index_entries(value: bytes, object_format: str) -> dict[str, _GitEntry]:
    entries: dict[str, _GitEntry] = {}
    for record in _nul_records(value, "Git index"):
        try:
            metadata, path_value = record.split(b"\t", 1)
            mode_value, oid_value, stage_value = metadata.split(b" ", 2)
        except ValueError as error:
            raise BuildError("Git index contains a malformed record") from error
        path = _decode_git_path(path_value)
        if stage_value != b"0":
            raise BuildError(f"Git index contains a non-stage-zero entry: {path!r}")
        if mode_value not in {b"100644", b"100755"}:
            raise BuildError(f"Git index contains a non-regular entry: {path!r}")
        if path in entries:
            raise BuildError(f"Git index contains a duplicate stage-zero path: {path!r}")
        entries[path] = _GitEntry(
            path=path,
            mode=int(mode_value, 8),
            oid=_validate_git_oid(oid_value, object_format),
        )
    return entries


def _require_canonical_index_flags(value: bytes, tracked_paths: set[str]) -> None:
    reported_paths: set[str] = set()
    for record in _nul_records(value, "Git index flags"):
        if len(record) < 3 or record[1:2] != b" ":
            raise BuildError("Git index flags contain a malformed record")
        tag = record[:1]
        path = _decode_git_path(record[2:])
        if path in reported_paths:
            raise BuildError(f"Git index flags contain a duplicate path: {path!r}")
        reported_paths.add(path)
        if tag == b"h":
            raise BuildError(f"Git index assume-unchanged flag is forbidden: {path!r}")
        if tag in {b"S", b"s"}:
            raise BuildError(f"Git index skip-worktree flag is forbidden: {path!r}")
        if tag != b"H":
            raise BuildError(f"Git index contains a hidden or non-canonical flag: {path!r}")
    if reported_paths != tracked_paths:
        raise BuildError("Git index flag inventory differs from HEAD")


def _git_blob_oid(content: bytes, object_format: str) -> str:
    digest = hashlib.new(object_format, usedforsecurity=False)
    digest.update(f"blob {len(content)}\0".encode())
    digest.update(content)
    return digest.hexdigest()


def _read_tracked_blob(
    canonical_root: Path,
    entry: _GitEntry,
    object_format: str,
) -> TrackedBlob:
    candidate = canonical_root.joinpath(*PurePosixPath(entry.path).parts)
    try:
        before = candidate.lstat()
    except OSError as error:
        raise BuildError(f"tracked worktree path is unavailable: {entry.path!r}") from error
    if not stat.S_ISREG(before.st_mode):
        raise BuildError(f"tracked worktree path is not a regular file: {entry.path!r}")
    expected_executable = entry.mode == int(b"100755", 8)
    actual_executable = bool(stat.S_IMODE(before.st_mode) & 0o111)
    if actual_executable != expected_executable:
        raise BuildError(f"tracked worktree executable mode differs from HEAD: {entry.path!r}")
    try:
        content = candidate.read_bytes()
        after = candidate.lstat()
    except OSError as error:
        raise BuildError(f"cannot read tracked worktree path: {entry.path!r}") from error
    state_before = (
        before.st_dev,
        before.st_ino,
        before.st_mode,
        before.st_size,
        before.st_mtime_ns,
    )
    state_after = (
        after.st_dev,
        after.st_ino,
        after.st_mode,
        after.st_size,
        after.st_mtime_ns,
    )
    if state_after != state_before:
        raise BuildError(f"tracked worktree path changed during attestation: {entry.path!r}")
    if _git_blob_oid(content, object_format) != entry.oid:
        raise BuildError(f"tracked worktree raw bytes differ from HEAD: {entry.path!r}")
    return TrackedBlob(
        path=entry.path,
        mode=entry.mode,
        oid=entry.oid,
        content=content,
    )


def _trusted_ignore_source_for_parent(
    canonical_root: Path,
    parent: str,
) -> str | None:
    parent_value = f"{parent.rstrip('/')}/".encode()
    completed = _attestation_git_raw(
        canonical_root,
        "check-ignore",
        "-z",
        "-v",
        "--no-index",
        "--stdin",
        input_data=parent_value + b"\0",
    )
    if completed.returncode == 1:
        return None
    if completed.returncode != 0:
        raise BuildError(
            f"cannot verify untracked ignore-control parent{_attestation_error(completed)}"
        )
    fields = _nul_records(completed.stdout, "Git ignore explanation")
    if len(fields) != 4 or fields[3] != parent_value:
        raise BuildError("Git returned a malformed ignore explanation")
    return _decode_git_path(fields[0])


def _require_no_untrusted_ignore_controls(
    canonical_root: Path,
    tracked_ignore_paths: set[str],
) -> None:
    controls = _attestation_git_bytes(
        canonical_root,
        "ls-files",
        "--others",
        "-z",
        "--",
        ".gitignore",
        ":(glob)**/.gitignore",
    )
    for record in _nul_records(controls, "untracked ignore-control inventory"):
        path = _decode_git_path(record)
        parent_path = PurePosixPath(path).parent
        if parent_path == PurePosixPath("."):
            raise BuildError(f"untracked ignore-control file is forbidden: {path!r}")
        source = _trusted_ignore_source_for_parent(
            canonical_root,
            parent_path.as_posix(),
        )
        if source not in tracked_ignore_paths:
            raise BuildError(f"untracked ignore-control file is forbidden: {path!r}")


def _require_no_untracked_nonignored(canonical_root: Path) -> None:
    untracked = _attestation_git_bytes(
        canonical_root,
        "ls-files",
        "--others",
        "--exclude-per-directory=.gitignore",
        "-z",
    )
    records = _nul_records(untracked, "untracked path inventory")
    if records:
        first_untracked = _decode_git_path(records[0])
        raise BuildError(f"source checkout has an untracked non-ignored path: {first_untracked!r}")


def _derive_attested_identity(canonical_root: Path) -> SourceIdentity:
    revision_value = _attestation_git_output(
        canonical_root,
        "rev-parse",
        "--verify",
        "HEAD^{commit}",
    )
    tree_value = _attestation_git_output(
        canonical_root,
        "rev-parse",
        "--verify",
        f"{revision_value}^{{tree}}",
    )
    epoch_value_text = _attestation_git_output(
        canonical_root,
        "show",
        "-s",
        "--no-show-signature",
        "--format=%ct",
        revision_value,
    )
    try:
        epoch_value = int(epoch_value_text)
    except ValueError as error:
        raise BuildError("Git commit epoch is not an integer") from error

    identity = SourceIdentity(revision_value, tree_value, epoch_value)
    identity.validate()
    return identity


def _derive_clean_attested_source(canonical_root: Path) -> SourceAttestation:
    identity = _derive_attested_identity(canonical_root)
    object_format = _attestation_git_output(
        canonical_root,
        "rev-parse",
        "--show-object-format",
    )
    if object_format not in {"sha1", "sha256"}:
        raise BuildError(f"unsupported Git object format: {object_format!r}")
    head_entries = _parse_head_entries(
        _attestation_git_bytes(
            canonical_root,
            "ls-tree",
            "-r",
            "-z",
            "--full-tree",
            identity.revision,
        ),
        object_format,
    )
    index_entries = _parse_index_entries(
        _attestation_git_bytes(
            canonical_root,
            "ls-files",
            "--stage",
            "-z",
        ),
        object_format,
    )
    if index_entries != head_entries:
        raise BuildError("Git index stage-zero blob/mode inventory differs from HEAD")
    _require_canonical_index_flags(
        _attestation_git_bytes(
            canonical_root,
            "ls-files",
            "-v",
            "-z",
        ),
        set(head_entries),
    )
    tracked_blobs = tuple(
        _read_tracked_blob(canonical_root, head_entries[path], object_format)
        for path in sorted(head_entries)
    )
    tracked_ignore_paths = {
        blob.path for blob in tracked_blobs if PurePosixPath(blob.path).name == ".gitignore"
    }
    _require_no_untrusted_ignore_controls(canonical_root, tracked_ignore_paths)
    _require_no_untracked_nonignored(canonical_root)
    confirmed = _derive_attested_identity(canonical_root)
    if confirmed != identity:
        raise BuildError("source checkout identity changed during attestation")
    return SourceAttestation(
        identity=identity,
        repository_root=canonical_root,
        object_format=object_format,
        tracked_blobs=tracked_blobs,
    )


def attest_source_checkout(
    revision: str | None,
    tree: str | None,
    epoch: int | None,
    *,
    repository_root: Path | None = None,
) -> SourceAttestation:
    """Derive and attest the clean canonical checkout before acceptance output."""
    selected_root = repository_root if repository_root is not None else REPOSITORY_ROOT
    if not selected_root.is_absolute():
        raise BuildError("canonical repository root must be an absolute path")
    try:
        canonical_root = selected_root.resolve(strict=True)
    except OSError as error:
        raise BuildError(f"canonical repository root is unavailable: {error}") from error
    if selected_root != canonical_root:
        raise BuildError("canonical repository root must not contain symlinks or aliases")
    reported_root_value = _attestation_git_output(
        canonical_root,
        "rev-parse",
        "--show-toplevel",
    )
    reported_root_path = Path(reported_root_value)
    if not reported_root_path.is_absolute():
        raise BuildError("Git reported a non-absolute repository root")
    try:
        reported_root = reported_root_path.resolve(strict=True)
    except OSError as error:
        raise BuildError(f"Git reported an invalid repository root: {error}") from error
    if reported_root_path != reported_root or reported_root != canonical_root:
        raise BuildError(
            f"canonical repository root mismatch: expected {canonical_root}, "
            f"Git reported {reported_root_path}"
        )

    attestation = _derive_clean_attested_source(canonical_root)
    identity = attestation.identity

    supplied_values = (
        ("revision", revision, identity.revision),
        ("tree", tree, identity.tree),
        ("epoch", epoch, identity.epoch),
    )
    for name, supplied, derived in supplied_values:
        if supplied is not None and supplied != derived:
            raise BuildError(
                f"supplied source {name} does not exactly match the canonical checkout"
            )
    final_attestation = _derive_clean_attested_source(canonical_root)
    if final_attestation != attestation:
        raise BuildError("source checkout state changed during attestation")
    return attestation


def _iter_regular_files(root: Path) -> list[tuple[str, Path]]:
    result: list[tuple[str, Path]] = []
    for path in root.rglob("*"):
        if path.is_symlink():
            raise BuildError(f"symlink is forbidden in artifact input: {path}")
        if path.is_file():
            relative = path.relative_to(root).as_posix()
            _safe_relative(relative)
            result.append((relative, path))
        elif path.exists() and not path.is_dir():
            raise BuildError(f"non-regular artifact input: {path}")
    result.sort(key=lambda item: item[0])
    return result


def tree_digest(root: Path) -> str:
    digest = hashlib.sha256()
    for relative, path in _iter_regular_files(root):
        encoded = relative.encode()
        digest.update(len(encoded).to_bytes(8, "big"))
        digest.update(encoded)
        digest.update(path.stat().st_size.to_bytes(8, "big"))
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    return digest.hexdigest()


def _copy_source_snapshot(
    destination: Path,
    attestation: SourceAttestation,
) -> None:
    _clear_generated_directory(destination)
    blobs = {blob.path: blob for blob in attestation.tracked_blobs}
    fixed_paths = {
        "updater/README.md": "README.md",
        "updater/build/runtime_prune.py": "build/runtime_prune.py",
        "updater/pyproject.toml": "pyproject.toml",
        "updater/uv.lock": "uv.lock",
    }
    selected: list[tuple[str, TrackedBlob]] = []
    for source_path, destination_path in fixed_paths.items():
        try:
            selected.append((destination_path, blobs[source_path]))
        except KeyError as error:
            raise BuildError(
                f"attested candidate is missing required Updater blob: {source_path}"
            ) from error
    source_prefix = "updater/src/"
    source_blobs = [
        blob for blob in attestation.tracked_blobs if blob.path.startswith(source_prefix)
    ]
    if not source_blobs:
        raise BuildError("attested candidate contains no tracked Updater source blobs")
    selected.extend((blob.path.removeprefix("updater/"), blob) for blob in source_blobs)
    selected.sort(key=lambda item: item[0])
    if len({path for path, _blob in selected}) != len(selected):
        raise BuildError("attested Updater snapshot contains duplicate destination paths")
    for relative, blob in selected:
        _safe_relative(relative)
        mode = 0o755 if blob.mode == int(b"100755", 8) else 0o644
        _write_bytes(destination / relative, blob.content, mode=mode)


def _build_definition_digest() -> str:
    digest = hashlib.sha256()
    paths = [UPDATER_ROOT / "Dockerfile"]
    paths.extend(
        path
        for path in BUILD_ROOT.glob("*.py")
        if path.is_file() and not path.name.startswith("test_")
    )
    for path in sorted(paths, key=lambda value: value.name):
        relative = path.relative_to(UPDATER_ROOT).as_posix().encode()
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        digest.update(path.read_bytes())
    return digest.hexdigest()


def _verify_toolchain(uv: Path, python: Path) -> None:
    uv_output = _run([str(uv), "--version"], cwd=UPDATER_ROOT, capture=True)
    python_output = _run([str(python), "--version"], cwd=UPDATER_ROOT, capture=True)
