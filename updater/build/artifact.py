@dataclass(frozen=True)
class Target:
    os: str
    architecture: str
    uv_platform: str

    @classmethod
    def parse(cls, value: str) -> Target:
        supported = {
            "linux/amd64": cls("linux", "amd64", "x86_64-manylinux_2_28"),
            "linux/arm64": cls("linux", "arm64", "aarch64-manylinux_2_28"),
        }
        try:
            return supported[value]
        except KeyError as error:
            raise BuildError(f"unsupported target platform: {value}") from error

    @property
    def docker(self) -> str:
        return f"{self.os}/{self.architecture}"

    @property
    def slug(self) -> str:
        return f"{self.os}-{self.architecture}"


@dataclass(frozen=True)
class SourceIdentity:
    revision: str
    tree: str
    epoch: int

    def validate(self) -> None:
        if not GIT_OBJECT_RE.fullmatch(self.revision):
            raise BuildError("source revision must be a lowercase Git object id")
        if not GIT_OBJECT_RE.fullmatch(self.tree):
            raise BuildError("source tree must be a lowercase Git object id")
        if self.epoch < 315_532_800:
            raise BuildError("SOURCE_DATE_EPOCH must be at or after 1980-01-01")


