def _extract_wheel(wheel: Path, destination: Path) -> None:
    with zipfile.ZipFile(wheel) as archive:
        for info in sorted(archive.infolist(), key=lambda item: item.filename):
            name = info.filename.rstrip("/")
            if not name:
                continue
            relative = _safe_relative(name)
            unix_mode = info.external_attr >> 16
            if stat.S_ISLNK(unix_mode):
                raise BuildError(f"wheel contains a symlink: {name}")
            target = destination.joinpath(*relative.parts)
            if info.is_dir():
                _ensure_generated_directory(target)
                continue
            _write_bytes(target, archive.read(info))


def _remove_python_cache(root: Path) -> None:
    for directory in sorted(root.rglob("__pycache__"), reverse=True):
        if directory.is_dir():
            _remove_generated_directory(directory)
    for suffix in ("*.pyc", "*.pyo"):
        for path in root.rglob(suffix):
            _unlink_generated_file(path)


def _metadata_value(path: Path, field: str) -> str:
    parser = email.parser.Parser()
    message = parser.parsestr(path.read_text(encoding="utf-8"))
    value = message.get(field)
    if value is None:
        raise BuildError(f"{path} is missing metadata field {field}")
    return value


def installed_distributions(site_packages: Path) -> list[dict[str, str]]:
    result = [
        {
            "name": _metadata_value(metadata, "Name").lower().replace("_", "-"),
            "version": _metadata_value(metadata, "Version"),
        }
        for metadata in sorted(site_packages.glob("*.dist-info/METADATA"))
    ]
    result.sort(key=lambda value: (value["name"], value["version"]))
    if not any(item["name"] == PACKAGE_NAME for item in result):
        raise BuildError("installed bundle does not contain the Updater package")
    if len({item["name"] for item in result}) != len(result):
        raise BuildError("installed bundle contains duplicate distribution names")
    return result


def _normalized_tar(
    source: Path,
    destination: Path,
    *,
    prefix: str | None,
    epoch: int,
    compress: bool,
) -> None:
    destination = _ensure_generated_parent(destination)
    raw_path = _require_under_tmp(destination.with_name(f".{destination.name}.tar"))
    if os.path.lexists(raw_path) and (raw_path.is_symlink() or not raw_path.is_file()):
        raise BuildError(f"refusing to replace non-file tar output: {raw_path}")
    with (
        raw_path.open("wb") as raw_handle,
        tarfile.open(fileobj=raw_handle, mode="w", format=tarfile.PAX_FORMAT) as archive,
    ):
        entries: list[tuple[str, Path | None, bool]] = []
        if prefix:
            entries.append((prefix.rstrip("/"), None, True))
        directories: set[str] = set()
        for relative, source_path in _iter_regular_files(source):
            output = f"{prefix.rstrip('/')}/{relative}" if prefix else relative
            parent = PurePosixPath(output).parent
            while parent.as_posix() not in {".", ""}:
                directories.add(parent.as_posix())
                parent = parent.parent
            entries.append((output, source_path, False))
        entries.extend(
            (directory, None, True)
            for directory in directories
            if not prefix or directory != prefix.rstrip("/")
        )
        entries.sort(key=lambda item: (item[0], not item[2]))
        for name, entry_path, is_directory in entries:
            info = tarfile.TarInfo(name)
            info.uid = 0
            info.gid = 0
            info.uname = ""
            info.gname = ""
            info.mtime = epoch
            info.pax_headers = {}
            if is_directory:
                info.type = tarfile.DIRTYPE
                info.mode = 0o755
                archive.addfile(info)
                continue
            if entry_path is None:
                raise BuildError(f"missing file for tar member: {name}")
            info.size = entry_path.stat().st_size
            info.mode = 0o755 if os.access(entry_path, os.X_OK) else 0o644
            with entry_path.open("rb") as handle:
                archive.addfile(info, handle)
    if compress:
        temporary = _require_under_tmp(destination.with_name(f".{destination.name}.writing"))
        if os.path.lexists(temporary) and (temporary.is_symlink() or not temporary.is_file()):
            raise BuildError(f"refusing to replace non-file temporary output: {temporary}")
        with (
            raw_path.open("rb") as source_handle,
            temporary.open("wb") as target_handle,
            gzip.GzipFile(
                filename="",
                fileobj=target_handle,
                mode="wb",
                compresslevel=9,
                mtime=epoch,
            ) as compressor,
        ):
            shutil.copyfileobj(source_handle, compressor)
        _unlink_generated_file(raw_path)
        _require_under_tmp(destination)
        _require_under_tmp(temporary)
        temporary.replace(destination)
    else:
        _require_under_tmp(destination)
        _require_under_tmp(raw_path)
        raw_path.replace(destination)
    destination.chmod(0o644)


def _extract_tar_safely(archive_path: Path, destination: Path) -> None:
    _clear_generated_directory(destination)
    with tarfile.open(archive_path, "r:*") as archive:
        for member in archive.getmembers():
            relative = _safe_relative(member.name.rstrip("/"))
            target = destination.joinpath(*relative.parts)
            if member.isdir():
                _ensure_generated_directory(target)
                continue
            if not member.isfile():
                raise BuildError(f"OCI archive has a non-regular member: {member.name}")
            source = archive.extractfile(member)
            if source is None:
                raise BuildError(f"cannot read OCI member: {member.name}")
            with source:
                _copy_generated_stream(source, target)


def _runtime_lock_packages(lock_path: Path) -> dict[str, dict[str, Any]]:
    document = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    packages: dict[str, dict[str, Any]] = {}
    for value in document.get("package", []):
        name = str(value["name"]).lower().replace("_", "-")
        if name in packages:
            raise BuildError(f"uv.lock contains duplicate package name: {name}")
        packages[name] = value
    return packages


def _locked_package_checksum(package: Mapping[str, Any]) -> str | None:
    """Return a wheel checksum only when the target wheel is unambiguous.

    An sdist hash never identifies installed runtime bytes.  Likewise, choosing
    one arbitrary wheel from a multi-platform lock would misstate provenance,
    so the optional package checksum is omitted unless exactly one distinct
    locked wheel digest exists.
    """

    wheels = package.get("wheels", [])
    hashes = {
        str(wheel.get("hash", ""))[7:]
        for wheel in wheels
        if isinstance(wheel, Mapping)
        and str(wheel.get("hash", "")).startswith("sha256:")
        and SHA256_RE.fullmatch(str(wheel.get("hash", ""))[7:])
    }
    return next(iter(hashes)) if len(hashes) == 1 else None


def _spdx_id(name: str, version: str) -> str:
    value = re.sub(r"[^A-Za-z0-9.-]+", "-", f"{name}-{version}").strip("-")
    return f"SPDXRef-Package-{value}"


def make_spdx(
    *,
    artifacts: Sequence[Mapping[str, Any]],
    dependency_artifact_path: str,
    runtime_packages: Sequence[Mapping[str, str]],
    lock_path: Path,
    namespace_digest: str | None = None,
) -> dict[str, Any]:
    lock_packages = _runtime_lock_packages(lock_path)
    normalized_artifacts: list[dict[str, str]] = []
    for index, item in enumerate(artifacts):
        path = _safe_relative(str(item.get("path", ""))).as_posix()
        digest = str(item.get("sha256", "")).removeprefix("sha256:")
        if not SHA256_RE.fullmatch(digest):
            raise BuildError(f"artifact {index} has an invalid SHA-256 digest")
        normalized_artifacts.append({"path": path, "sha256": digest})
    normalized_artifacts.sort(key=lambda item: item["path"])
    paths = [item["path"] for item in normalized_artifacts]
    digests = [item["sha256"] for item in normalized_artifacts]
    if not normalized_artifacts or len(paths) != len(set(paths)):
        raise BuildError("SPDX artifact paths must be non-empty and unique")
    if len(digests) != len(set(digests)):
        raise BuildError("SPDX artifact digests must be unique")
    dependency_path = _safe_relative(dependency_artifact_path).as_posix()
    artifact_by_path = {item["path"]: item for item in normalized_artifacts}
    if dependency_path not in artifact_by_path:
        raise BuildError("SPDX dependency artifact must name a statement artifact")
    namespace_value = namespace_digest or normalized_artifacts[0]["sha256"]
    namespace_value = namespace_value.removeprefix("sha256:")
    if namespace_value not in set(digests):
        raise BuildError("SPDX namespace digest must name a statement artifact")

    packages: list[dict[str, Any]] = []
    artifact_ids: dict[str, str] = {}
    relationships: list[dict[str, str]] = []
    for item in normalized_artifacts:
        package_id = f"SPDXRef-Package-Artifact-{item['sha256']}"
        artifact_ids[item["path"]] = package_id
        packages.append(
            {
                "SPDXID": package_id,
                "checksums": [{"algorithm": "SHA256", "checksumValue": item["sha256"]}],
                "copyrightText": "NOASSERTION",
                "downloadLocation": "NOASSERTION",
                "filesAnalyzed": False,
                "licenseConcluded": "NOASSERTION",
                "licenseDeclared": "NOASSERTION",
                "name": item["path"],
                "primaryPackagePurpose": "APPLICATION",
                "versionInfo": PACKAGE_VERSION,
            }
        )
        relationships.append(
            {
                "relatedSpdxElement": package_id,
                "relationshipType": "DESCRIBES",
                "spdxElementId": "SPDXRef-DOCUMENT",
            }
        )

    dependency_root_id = artifact_ids[dependency_path]
    seen = {PACKAGE_NAME}
    for item in sorted(runtime_packages, key=lambda value: (value["name"], value["version"])):
        name = item["name"]
        version = item["version"]
        if name == PACKAGE_NAME:
            if version != PACKAGE_VERSION:
                raise BuildError("installed project version disagrees with pyproject.toml")
            continue
        if name in seen:
            raise BuildError(f"duplicate runtime package in SBOM input: {name}")
        seen.add(name)
        locked = lock_packages.get(name)
        if locked is None or str(locked.get("version")) != version:
            raise BuildError(f"installed runtime package disagrees with uv.lock: {name}=={version}")
        package: dict[str, Any] = {
            "SPDXID": _spdx_id(name, version),
            "copyrightText": "NOASSERTION",
            "downloadLocation": "NOASSERTION",
            "filesAnalyzed": False,
            "licenseConcluded": "NOASSERTION",
            "licenseDeclared": "NOASSERTION",
            "name": name,
            "primaryPackagePurpose": "LIBRARY",
            "versionInfo": version,
        }
        checksum = _locked_package_checksum(locked)
        if checksum is not None:
            package["checksums"] = [{"algorithm": "SHA256", "checksumValue": checksum}]
        packages.append(package)
        relationships.append(
            {
                "relatedSpdxElement": package["SPDXID"],
                "relationshipType": "DEPENDS_ON",
                "spdxElementId": dependency_root_id,
            }
        )
    packages.sort(key=lambda value: value["SPDXID"])
    relationships.sort(
        key=lambda value: (
            value["spdxElementId"],
            value["relationshipType"],
            value["relatedSpdxElement"],
        )
    )
    return {
        "SPDXID": "SPDXRef-DOCUMENT",
        "creationInfo": {
            "created": "1970-01-01T00:00:00Z",
            "creators": ["Tool: bgmss-updater-build/1"],
        },
        "dataLicense": "CC0-1.0",
        "documentNamespace": (
            f"https://spdx.bangumi-staff-stats.invalid/updater/sha256-{namespace_value}"
        ),
        "name": f"{PACKAGE_NAME}-{PACKAGE_VERSION}-{namespace_value[:16]}",
        "packages": packages,
        "relationships": relationships,
        "spdxVersion": "SPDX-2.3",
    }


def verify_spdx_artifact_coverage(
    document: Mapping[str, Any],
    artifacts: Sequence[Mapping[str, Any]],
) -> None:
    artifact_digests: dict[str, str] = {}
    for item in artifacts:
        path = _safe_relative(str(item.get("path", ""))).as_posix()
        digest = str(item.get("sha256", "")).removeprefix("sha256:")
        if not SHA256_RE.fullmatch(digest):
            raise BuildError(f"SPDX artifact has an invalid SHA-256 digest: {path}")
        if digest in artifact_digests:
            raise BuildError("SPDX statement artifact digests must be unique")
        artifact_digests[digest] = path

    packages = document.get("packages")
    relationships = document.get("relationships")
    if not isinstance(packages, list) or not isinstance(relationships, list):
        raise BuildError("SPDX packages and relationships must be arrays")
    packages_by_id: dict[str, Mapping[str, Any]] = {}
    for package in packages:
        if not isinstance(package, Mapping):
            raise BuildError("SPDX package must be an object")
        package_id = str(package.get("SPDXID", ""))
        if not package_id or package_id in packages_by_id:
            raise BuildError("SPDX package IDs must be non-empty and unique")
        packages_by_id[package_id] = package

    described_ids = {
        str(relationship.get("relatedSpdxElement", ""))
        for relationship in relationships
        if isinstance(relationship, Mapping)
        and relationship.get("spdxElementId") == "SPDXRef-DOCUMENT"
        and relationship.get("relationshipType") == "DESCRIBES"
    }
    document_describes = document.get("documentDescribes", [])
    if not isinstance(document_describes, list):
        raise BuildError("SPDX documentDescribes must be an array")
    described_ids.update(str(value) for value in document_describes)

    described_digests: set[str] = set()
    digest_owners: dict[str, list[str]] = {digest: [] for digest in artifact_digests}
    for package_id, package in packages_by_id.items():
        checksums = package.get("checksums", [])
        if not isinstance(checksums, list):
            raise BuildError(f"SPDX package checksums must be an array: {package_id}")
        for checksum in checksums:
            if not isinstance(checksum, Mapping):
                raise BuildError(f"SPDX checksum must be an object: {package_id}")
            digest = str(checksum.get("checksumValue", ""))
            if checksum.get("algorithm") == "SHA256" and digest in digest_owners:
                digest_owners[digest].append(package_id)
    for package_id in described_ids:
        package = packages_by_id.get(package_id)
        if package is None:
            raise BuildError(f"SPDX DESCRIBES references an unknown package: {package_id}")
        checksums = package.get("checksums", [])
        if (
            not isinstance(checksums, list)
            or len(checksums) != 1
            or not isinstance(checksums[0], Mapping)
            or checksums[0].get("algorithm") != "SHA256"
        ):
            raise BuildError(f"SPDX described package must have one SHA256: {package_id}")
        digest = str(checksums[0].get("checksumValue", ""))
        if digest not in artifact_digests:
            raise BuildError(
                f"SPDX described package checksum is not a statement artifact: {package_id}"
            )
        if digest in described_digests:
            raise BuildError("SPDX artifact digest is described more than once")
        described_digests.add(digest)
    if described_digests != set(artifact_digests):
        missing = sorted(set(artifact_digests) - described_digests)
        raise BuildError(f"SPDX does not describe every statement artifact: {missing}")
    for digest, owners in digest_owners.items():
        if len(owners) != 1 or owners[0] not in described_ids:
            raise BuildError(
                f"SPDX artifact digest must have one described package owner: {digest}"
            )


def _wheel_metadata(wheel: Path) -> dict[str, Any]:
    with zipfile.ZipFile(wheel) as archive:
        names = sorted(info.filename for info in archive.infolist() if not info.is_dir())
        metadata_names = [name for name in names if name.endswith(".dist-info/METADATA")]
        wheel_names = [name for name in names if name.endswith(".dist-info/WHEEL")]
        if len(metadata_names) != 1 or len(wheel_names) != 1:
            raise BuildError("wheel must contain exactly one METADATA and WHEEL")
        parser = email.parser.Parser()
        metadata = parser.parsestr(archive.read(metadata_names[0]).decode())
        wheel_message = parser.parsestr(archive.read(wheel_names[0]).decode())
        if metadata.get("Name", "").lower().replace("_", "-") != PACKAGE_NAME:
            raise BuildError("wheel package name is not the Updater package")
        if metadata.get("Version") != PACKAGE_VERSION:
            raise BuildError("wheel package version is unexpected")
        tags = sorted(wheel_message.get_all("Tag", []))
    return {
        "fileCount": len(names),
        "name": PACKAGE_NAME,
        "tags": tags,
        "version": PACKAGE_VERSION,
    }


def _parse_oci_metadata(oci_layout: Path) -> dict[str, Any]:
    try:
        index = json.loads((oci_layout / "index.json").read_text(encoding="utf-8"))
        manifests = index["manifests"]
    except (KeyError, json.JSONDecodeError, OSError) as error:
        raise BuildError(f"invalid OCI index: {error}") from error
    if len(manifests) != 1:
        raise BuildError("OCI index must contain exactly one runtime manifest")
    descriptor = manifests[0]
    digest = str(descriptor.get("digest", ""))
    if not digest.startswith("sha256:") or not SHA256_RE.fullmatch(digest[7:]):
        raise BuildError("OCI manifest digest is not SHA-256")
    manifest_path = oci_layout / "blobs" / "sha256" / digest[7:]
    if sha256_file(manifest_path) != digest[7:]:
        raise BuildError("OCI manifest blob digest mismatch")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    config = manifest.get("config", {})
    config_digest = str(config.get("digest", ""))
    if not config_digest.startswith("sha256:") or not SHA256_RE.fullmatch(config_digest[7:]):
        raise BuildError("OCI config digest is not SHA-256")
    config_path = oci_layout / "blobs" / "sha256" / config_digest[7:]
    if sha256_file(config_path) != config_digest[7:]:
        raise BuildError("OCI config blob digest mismatch")
    layers: list[dict[str, Any]] = []
    for layer in manifest.get("layers", []):
        layer_digest = str(layer.get("digest", ""))
        if not layer_digest.startswith("sha256:") or not SHA256_RE.fullmatch(layer_digest[7:]):
            raise BuildError("OCI layer digest is not SHA-256")
        layer_path = oci_layout / "blobs" / "sha256" / layer_digest[7:]
        if sha256_file(layer_path) != layer_digest[7:]:
            raise BuildError("OCI layer blob digest mismatch")
        layers.append(
            {
                "digest": layer_digest,
                "mediaType": layer["mediaType"],
                "size": int(layer["size"]),
            }
        )
    return {
        "config": {
            "digest": config_digest,
            "mediaType": config["mediaType"],
            "size": int(config["size"]),
        },
        "layers": layers,
        "manifest": {
            "digest": digest,
            "mediaType": descriptor["mediaType"],
            "size": int(descriptor["size"]),
        },
    }


def _build_wheel_and_bundle(
    *,
    snapshot: Path,
    work_root: Path,
    artifacts: Path,
    uv: Path,
    python: Path,
    target: Target,
    identity: SourceIdentity,
) -> tuple[Path, Path, list[dict[str, str]]]:
    environment = _uv_environment(work_root, python, identity.epoch)
    _run(
        [
            str(uv),
            "sync",
            "--frozen",
            "--python",
            str(python),
            "--no-install-project",
        ],
        cwd=snapshot,
        env=environment,
    )
    build_constraints = work_root / "build-constraints.txt"
    runtime_requirements = work_root / "runtime-requirements.txt"
    _ensure_generated_parent(build_constraints)
    _ensure_generated_parent(runtime_requirements)
    _run(
        [
            str(uv),
            "export",
            "--frozen",
            "--offline",
            "--only-dev",
            "--no-emit-project",
            "--no-annotate",
            "--no-header",
            "--output-file",
            str(build_constraints),
        ],
        cwd=snapshot,
        env=environment,
    )
    _run(
        [
            str(uv),
            "export",
            "--frozen",
            "--offline",
            "--no-dev",
            "--no-emit-project",
            "--no-annotate",
            "--no-header",
            "--output-file",
            str(runtime_requirements),
        ],
        cwd=snapshot,
        env=environment,
    )
    warmup_dist = work_root / "warmup-dist"
    _ensure_generated_directory(warmup_dist)
    _run(
        [
            str(uv),
            "build",
            "--wheel",
            "--python",
            str(python),
            "--out-dir",
            str(warmup_dist),
            "--build-constraints",
            str(build_constraints),
            "--require-hashes",
            "--no-create-gitignore",
        ],
        cwd=snapshot,
        env=environment,
    )
    _remove_generated_directory(warmup_dist)
    dist = work_root / "dist"
    _ensure_generated_directory(dist)
    _run(
        [
            str(uv),
            "build",
            "--offline",
            "--wheel",
            "--python",
            str(python),
            "--out-dir",
            str(dist),
            "--build-constraints",
            str(build_constraints),
            "--require-hashes",
            "--no-create-gitignore",
        ],
        cwd=snapshot,
        env=environment,
    )
    wheels = sorted(dist.glob("*.whl"))
    if len(wheels) != 1:
        raise BuildError("uv build did not emit exactly one wheel")
    _wheel_metadata(wheels[0])
    wheel_output = artifacts / wheels[0].name
    _copy_generated_file(wheels[0], wheel_output, mode=0o644)

    runtime_install = [
        str(uv),
        "pip",
        "install",
        "--python-version",
        PYTHON_VERSION,
        "--python-platform",
        target.uv_platform,
        "--only-binary",
        ":all:",
        "--require-hashes",
        "--requirements",
        str(runtime_requirements),
    ]
    warmup_site_packages = work_root / "warmup-site-packages"
    _ensure_generated_parent(warmup_site_packages)
    _run(
        [*runtime_install, "--target", str(warmup_site_packages)],
        cwd=snapshot,
        env=environment,
    )
    _remove_generated_directory(warmup_site_packages)
    bundle_root = work_root / "bundle-root"
    site_packages = bundle_root / "site-packages"
    _ensure_generated_directory(site_packages)
    _run(
        [*runtime_install, "--offline", "--target", str(site_packages)],
        cwd=snapshot,
        env=environment,
    )
    _extract_wheel(wheels[0], site_packages)
    try:
        prune_runtime_tree(site_packages)
    except RuntimePruneError as error:
        raise BuildError(f"runtime development-content pruning failed: {error}") from error
    _remove_python_cache(site_packages)
    runtime_packages = installed_distributions(site_packages)
    launcher = bundle_root / "bin" / "bgmss-updater"
    _write_bytes(
        launcher,
        (
            b"#!/usr/bin/env python3\n"
            b"from pathlib import Path\n"
            b"import sys\n"
            b"sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'site-packages'))\n"
            b"from bangumi_staff_stats_updater.cli import run\n"
            b"run()\n"
        ),
        mode=0o755,
    )
    _write_bytes(
        bundle_root / "bundle-metadata.json",
        canonical_json(
            {
                "component": COMPONENT_ID,
                "package": {"name": PACKAGE_NAME, "version": PACKAGE_VERSION},
                "python": PYTHON_VERSION,
                "runtimePackages": runtime_packages,
                "schemaVersion": "bgmss-updater-runtime-bundle-v1",
                "target": {"architecture": target.architecture, "os": target.os},
            }
        ),
    )
    bundle_output = artifacts / f"updater-runtime-{PACKAGE_VERSION}-{target.slug}.tar.gz"
    _normalized_tar(
        bundle_root,
        bundle_output,
        prefix="updater-runtime",
        epoch=identity.epoch,
        compress=True,
    )
    return wheel_output, bundle_output, runtime_packages


