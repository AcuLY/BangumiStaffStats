def _validated_builder_name(value: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,127}", value) is None:
        raise BuildError("Buildx builder name must be a safe non-option token")
    return value


def _validate_buildx_inspection(value: str, *, builder: str | None) -> str:
    name_match = re.search(r"(?m)^Name:\s+(\S+)\s*$", value)
    driver_match = re.search(r"(?m)^Driver:\s+(\S+)\s*$", value)
    options = re.findall(r'(?m)^Driver Options:\s+image="?([^"\s]+)"?\s*$', value)
    statuses = re.findall(r"(?m)^Status:\s+(\S+)\s*$", value)
    versions = re.findall(r"(?m)^BuildKit version:\s+v?(\S+)\s*$", value)
    if name_match is None:
        raise BuildError("Buildx inspection did not report a builder name")
    actual_builder = _validated_builder_name(name_match.group(1))
    if builder is not None and actual_builder != _validated_builder_name(builder):
        raise BuildError(f"Buildx inspection name must equal {builder}")
    if driver_match is None or driver_match.group(1) != "docker-container":
        raise BuildError("Buildx builder must use the docker-container driver")
    if options != [BUILDKIT_IMAGE]:
        raise BuildError("Buildx builder driver image is not the exact reviewed digest pin")
    if statuses != ["running"]:
        raise BuildError("Buildx builder must have exactly one running node")
    if versions != [BUILDKIT_VERSION]:
        raise BuildError(f"BuildKit must equal {BUILDKIT_VERSION}")
    return actual_builder


def _verify_docker_toolchain(docker: Path, *, builder: str | None) -> str:
    version_output = _run(
        [str(docker), "buildx", "version"],
        cwd=REPOSITORY_ROOT,
        capture=True,
    )
    match = re.search(r"\bv?([0-9]+\.[0-9]+\.[0-9]+)\b", version_output)
    if match is None or match.group(1) != DOCKER_BUILDX_VERSION:
        raise BuildError(f"expected Docker Buildx {DOCKER_BUILDX_VERSION}, got {version_output!r}")
    inspect_command = [str(docker), "buildx", "inspect"]
    if builder is not None:
        inspect_command.append(_validated_builder_name(builder))
    inspection = _run(
        inspect_command,
        cwd=REPOSITORY_ROOT,
        capture=True,
    )
    return _validate_buildx_inspection(inspection, builder=builder)


